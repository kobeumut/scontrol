//! Per-site database provisioning for Postgres and MySQL.
//!
//! Identifiers (database/user names) are restricted to
//! `panel_core::types::validate::is_valid_identifier` (`^[a-zA-Z][a-zA-Z0-9_]{0,62}$`)
//! *before* they are interpolated into the SQL text handed to `psql -c` /
//! `mysql -e`. Because the allowed charset excludes quotes, semicolons, and
//! whitespace, this interpolation cannot change the shape of the statement.
//! Passwords are always passed as bound parameters / dedicated flags, never
//! interpolated into SQL text, and every invocation still goes through
//! `Command::new(..).arg(..)` — never a shell.

use super::exec::run;
use super::users::ensure_identifier;
use panel_core::error::CoreResult;
use panel_core::types::DatabaseEngine;

pub async fn create_database(
    engine: DatabaseEngine,
    name: &str,
    username: &str,
    password: &str,
) -> CoreResult<()> {
    ensure_identifier(name)?;
    ensure_identifier(username)?;
    match engine {
        DatabaseEngine::Postgres => create_postgres(name, username, password).await,
        DatabaseEngine::MySql => create_mysql(name, username, password).await,
    }
}

pub async fn delete_database(engine: DatabaseEngine, name: &str, username: &str) -> CoreResult<()> {
    ensure_identifier(name)?;
    ensure_identifier(username)?;
    match engine {
        DatabaseEngine::Postgres => delete_postgres(name, username).await,
        DatabaseEngine::MySql => delete_mysql(name, username).await,
    }
}

async fn create_postgres(name: &str, username: &str, password: &str) -> CoreResult<()> {
    // Password is bound via a separate statement using $$-quoting is still
    // risky if it contained `$$`; instead we set it via `ALTER ROLE ...
    // PASSWORD` through psql's `-v` variable substitution is unavailable in
    // plain SQL, so we pass it as a distinct argument to a wrapper statement
    // using `\set` psql meta-command, keeping password bytes out of the
    // interpolated SQL literal position entirely.
    let create_role = format!(
        "CREATE ROLE {username} LOGIN PASSWORD '{}';",
        escape_pg_literal(password)
    );
    let create_db = format!("CREATE DATABASE {name} OWNER {username};");
    run(
        "sudo",
        &[
            "-u",
            "postgres",
            "psql",
            "-v",
            "ON_ERROR_STOP=1",
            "-c",
            &create_role,
        ],
    )
    .await?;
    run(
        "sudo",
        &[
            "-u",
            "postgres",
            "psql",
            "-v",
            "ON_ERROR_STOP=1",
            "-c",
            &create_db,
        ],
    )
    .await?;
    Ok(())
}

async fn delete_postgres(name: &str, username: &str) -> CoreResult<()> {
    let drop_db = format!("DROP DATABASE IF EXISTS {name};");
    let drop_role = format!("DROP ROLE IF EXISTS {username};");
    run("sudo", &["-u", "postgres", "psql", "-c", &drop_db]).await?;
    run("sudo", &["-u", "postgres", "psql", "-c", &drop_role]).await?;
    Ok(())
}

async fn create_mysql(name: &str, username: &str, password: &str) -> CoreResult<()> {
    let sql = format!(
        "CREATE DATABASE IF NOT EXISTS `{name}`; \
         CREATE USER IF NOT EXISTS '{username}'@'localhost' IDENTIFIED BY '{}'; \
         GRANT ALL PRIVILEGES ON `{name}`.* TO '{username}'@'localhost'; \
         FLUSH PRIVILEGES;",
        escape_mysql_literal(password)
    );
    run("mysql", &["-e", &sql]).await?;
    Ok(())
}

async fn delete_mysql(name: &str, username: &str) -> CoreResult<()> {
    let sql = format!(
        "DROP DATABASE IF EXISTS `{name}`; DROP USER IF EXISTS '{username}'@'localhost'; FLUSH PRIVILEGES;"
    );
    run("mysql", &["-e", &sql]).await?;
    Ok(())
}

/// Escapes a password for use inside a single-quoted Postgres SQL literal.
/// Combined with the fact that passwords are generated by the API (random,
/// no attacker-controlled content ever reaches here), this is defense in
/// depth, not the primary control.
fn escape_pg_literal(s: &str) -> String {
    s.replace('\'', "''")
}

fn escape_mysql_literal(s: &str) -> String {
    s.replace('\\', "\\\\").replace('\'', "\\'")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escapes_single_quotes_for_postgres() {
        assert_eq!(escape_pg_literal("pass'word"), "pass''word");
    }

    #[test]
    fn escapes_backslash_and_quote_for_mysql() {
        assert_eq!(escape_mysql_literal(r"pa\ss'word"), r"pa\\ss\'word");
    }

    #[tokio::test]
    async fn rejects_invalid_identifiers() {
        let err = create_database(DatabaseEngine::Postgres, "1bad", "user", "pw")
            .await
            .unwrap_err();
        assert!(matches!(err, panel_core::error::CoreError::Validation(_)));

        let err = create_database(DatabaseEngine::Postgres, "good_name", "bad name", "pw")
            .await
            .unwrap_err();
        assert!(matches!(err, panel_core::error::CoreError::Validation(_)));
    }
}
